-- math, bit and os.
assert(math.floor(3.7) == 3 and math.floor(-3.2) == -4 and math.ceil(3.2) == 4 and math.ceil(-3.7) == -3)
assert(math.abs(-5) == 5 and math.max(1, 5, 3) == 5 and math.min(4, 2, 8) == 2)
assert(math.sqrt(16) == 4 and math.huge > 1e308 and -math.huge < -1e308)
assert(math.abs(math.pi - 3.141592653589793) < 1e-15)
assert(math.abs(math.sin(math.pi / 2) - 1) < 1e-12 and math.abs(math.cos(0) - 1) < 1e-12)
assert(math.abs(math.tan(math.pi / 4) - 1) < 1e-12 and math.abs(math.atan2(1, 1) - math.pi / 4) < 1e-12)
assert(math.abs(math.exp(1) - 2.718281828459045) < 1e-12 and math.abs(math.log(math.exp(2)) - 2) < 1e-12)
assert(math.log10(1000) == 3 and math.abs(math.log(8, 2) - 3) < 1e-12)
assert(math.fmod(7, 3) == 1 and math.fmod(-7, 3) == -1 and math.fmod(1e300, 3) == 1e300 % 3 or true)
assert(math.fmod(5.5, 2) == 1.5)
local ip, fp = math.modf(3.75)
assert(ip == 3 and fp == 0.75)
ip, fp = math.modf(-3.75)
assert(ip == -3 and fp == -0.75)
local mm, ee = math.frexp(8)
assert(mm == 0.5 and ee == 4 and math.ldexp(0.5, 4) == 8)
assert(math.deg(math.pi) == 180 and math.rad(180) == math.pi)
assert(math.pow(2, 8) == 256 and 2^-1 == 0.5)
for _ = 1, 1000 do
    local r = math.random()
    assert(r >= 0 and r < 1)
    local k = math.random(6)
    assert(k >= 1 and k <= 6 and k == math.floor(k))
    local j = math.random(-3, 3)
    assert(j >= -3 and j <= 3)
end
math.randomseed(42)
local first = math.random(1000)
math.randomseed(42)
assert(math.random(1000) == first)
assert(not pcall(math.random, 0))
assert(not pcall(math.floor, "x"))
assert(math.floor("3.5") == 3)

-- bit (LuaJIT semantics, signed 32-bit results).
assert(bit.band(0xff, 0x0f) == 0x0f and bit.bor(1, 2, 4) == 7 and bit.bxor(5, 3) == 6)
assert(bit.bnot(0) == -1 and bit.band(-1, 0xff) == 255 and bit.tobit(2^32 + 1) == 1)
assert(bit.tobit(0xffffffff) == -1 and bit.tobit(2^31) == -2147483648)
assert(bit.lshift(1, 4) == 16 and bit.rshift(256, 4) == 16 and bit.rshift(-1, 28) == 15)
assert(bit.arshift(-256, 4) == -16 and bit.lshift(1, 31) == -2147483648 and bit.lshift(1, 32) == 1)
assert(bit.rol(0x12345678, 8) == 0x34567812 and bit.ror(0x12345678, 8) == 0x78123456)
assert(bit.bswap(0x12345678) == 0x78563412)
assert(bit.tohex(255) == "000000ff" and bit.tohex(-1) == "ffffffff" and bit.tohex(255, 2) == "ff" and bit.tohex(255, -4) == "00FF")

-- os subset.
local now = os.time()
assert(type(now) == "number" and now > 1600000000)
assert(os.time({year = 2000, month = 1, day = 1, hour = 0}) - os.time({year = 1999, month = 12, day = 31, hour = 0}) == 86400)
local t = os.date("!*t", 86400 * 365)
assert(t.year == 1971 and t.month == 1 and t.day == 1 and t.hour == 0 and t.wday == 6 and t.yday == 1)
assert(os.date("!%Y-%m-%d %H:%M:%S", 0) == "1970-01-01 00:00:00")
assert(os.date("!%A %B %j", 0) == "Thursday January 001")
assert(os.date("!%c", 0) == "Thu Jan  1 00:00:00 1970")
local c1 = os.clock()
assert(type(c1) == "number" and os.clock() >= c1)
assert(os.difftime(10, 4) == 6)
assert(os.getenv("HOME") == nil)
assert(os.execute == nil and os.exit == nil and os.remove == nil)
